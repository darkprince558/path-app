import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';

// Export the actual validators, including refinements, without Next.js/DB imports.
// The backend sources remain authoritative; --check detects any runtime drift.
const contractUrl = new URL('../src/lib/capture/contract.ts', import.meta.url);
const scansUrl = new URL('../src/lib/api/scans.ts', import.meta.url);
const outputUrl = new URL('../../../apps/capture/processor/contract.mjs', import.meta.url);
const contract = await readFile(contractUrl, 'utf8');
const scans = await readFile(scansUrl, 'utf8');
const source = ts.createSourceFile('scans.ts', scans, ts.ScriptTarget.Latest, true);
const transform = source.statements.find(statement => ts.isVariableStatement(statement) &&
  statement.declarationList.declarations.some(declaration => declaration.name.getText(source) === 'transform'));
if (!transform) throw new Error('Authoritative transform validator was not found');
const contractSource = ts.createSourceFile('contract.ts', contract, ts.ScriptTarget.Latest, true);
const body = contractSource.statements.filter(statement => !ts.isImportDeclaration(statement)).map(statement => statement.getText(contractSource)).join('\n');
const input = `import { z } from 'zod';\n${transform.getText(source)}\n${body}\n`;
const digest = createHash('sha256').update(input).digest('hex');
const generated = `// Generated by services/api/scripts/export-capture-contract.ts. Do not edit.\n// Backend validators SHA-256: ${digest}\n` +
  ts.transpileModule(input, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
if (process.argv.includes('--check')) {
  if (await readFile(outputUrl, 'utf8') !== generated) throw new Error('CPU contract is stale; run npm run contract:export in services/api');
  console.log('CPU validators match the authoritative backend schemas.');
} else {
  await writeFile(outputUrl, generated);
  console.log('Exported backend capture validators for the standalone CPU processor.');
}
